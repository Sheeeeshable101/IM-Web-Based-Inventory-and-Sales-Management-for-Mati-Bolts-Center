CREATE TABLE IF NOT EXISTS public.category (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  description text
);

CREATE TABLE IF NOT EXISTS public.supplier (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text,
  email text,
  address text
);

CREATE TABLE IF NOT EXISTS public.customer (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text,
  email text,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public."user" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  username text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('Admin', 'Staff')),
  active boolean NOT NULL DEFAULT true,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.product (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  category_id bigint NOT NULL REFERENCES public.category(id) ON DELETE RESTRICT,
  supplier_id bigint REFERENCES public.supplier(id) ON DELETE SET NULL,
  size text,
  material text,
  price numeric(12, 2) NOT NULL CHECK (price >= 0),
  stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  reorder_level integer NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.sales_order (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint REFERENCES public.customer(id) ON DELETE SET NULL,
  user_id bigint NOT NULL REFERENCES public."user"(id) ON DELETE RESTRICT,
  total_amount numeric(12, 2) NOT NULL CHECK (total_amount >= 0),
  status text NOT NULL DEFAULT 'Completed' CHECK (status IN ('Pending', 'Completed', 'Cancelled')),
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.order_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sales_order_id bigint NOT NULL REFERENCES public.sales_order(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.product(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
  line_total numeric(12, 2) NOT NULL CHECK (line_total >= 0),
  UNIQUE (sales_order_id, product_id)
);

CREATE TABLE IF NOT EXISTS public.stock_in (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.product(id) ON DELETE RESTRICT,
  supplier_id bigint REFERENCES public.supplier(id) ON DELETE SET NULL,
  user_id bigint NOT NULL REFERENCES public."user"(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  cost_per_unit numeric(12, 2) NOT NULL CHECK (cost_per_unit >= 0),
  notes text,
  received_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS product_category_id_idx ON public.product(category_id);
CREATE INDEX IF NOT EXISTS product_supplier_id_idx ON public.product(supplier_id);
CREATE INDEX IF NOT EXISTS sales_order_created_at_idx ON public.sales_order(created_at DESC);
CREATE INDEX IF NOT EXISTS sales_order_user_id_idx ON public.sales_order(user_id);
CREATE INDEX IF NOT EXISTS order_item_sales_order_id_idx ON public.order_item(sales_order_id);
CREATE INDEX IF NOT EXISTS order_item_product_id_idx ON public.order_item(product_id);
CREATE INDEX IF NOT EXISTS stock_in_received_at_idx ON public.stock_in(received_at DESC);

CREATE OR REPLACE VIEW public.v_low_stock AS
SELECT
  p.id,
  p.sku,
  p.name,
  p.category_id,
  c.name AS category_name,
  p.stock_quantity,
  p.reorder_level
FROM public.product AS p
JOIN public.category AS c ON c.id = p.category_id
WHERE p.stock_quantity <= p.reorder_level;

